; Routine: MLDAT
; Purpose: MONITOR load data routine - invoked from MLHED load sequence.
;          Receives file data block from device into memory via DBRCV.
; Inputs: protocol-driven, FSIZE and SADRS prepared by MLHED
; Outputs: receives data via DBRCV, reports result
; Clobbers: A, HL, B, DE
MLDAT:
		DI
		PUSH	DE
		PUSH	BC
		PUSH	HL
		LD		A,94H
		CALL	MCMD
		AND		A
		JP		NZ,MERR

		CALL	RCVBYTE
		AND		A
		JP		NZ,MERR

		CALL	RCVBYTE
		AND		A
		JP		NZ,MERR

		LD		DE,FSIZE
		LD		A,(DE)
		CALL	SNDBYTE
		INC		DE
		LD		A,(DE)
		CALL	SNDBYTE
		CALL	DBRCV

		CALL	RCVBYTE
		AND		A
		JP		NZ,MERR

		JR		MRET

